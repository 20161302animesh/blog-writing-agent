ANSI = re.compile(r"\x1b\[[0-9;]*m")
FORMATTER = HtmlFormatter(nowrap=True)


def code_html(source: str, lang: str = "python") -> str:
    try:
        lexer = get_lexer_by_name(lang or "text")
    except ClassNotFound:
        lexer = get_lexer_by_name("text")
    return highlight(source, lexer, FORMATTER).rstrip("\n")


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


md = MarkdownIt("commonmark", {"html": False}).enable("table")
md.options["highlight"] = lambda src, lang, attrs: (
    f'<pre class="code"><code>{code_html(src, lang)}</code></pre>'
)


def render_markdown(text: str, toc: list) -> str:
    out = md.render(text)

    def add_id(m: re.Match) -> str:
        inner = m.group(1)
        label = re.sub(r"<[^>]+>", "", html.unescape(inner))
        anchor = slugify(label)
        toc.append((anchor, label))
        return f'<h2 id="{anchor}">{inner}</h2>'

    return re.sub(r"<h2>(.*?)</h2>", add_id, out)


def join(src) -> str:
    return "".join(src) if isinstance(src, list) else src


def render_output(o: dict) -> str:
    kind = o["output_type"]
    if kind == "stream":
        text = ANSI.sub("", join(o["text"])).rstrip("\n")
        cls = "out-text err" if o.get("name") == "stderr" else "out-text"
        return f'<pre class="{cls}">{html.escape(text)}</pre>'
    if kind in ("display_data", "execute_result"):
        data = o["data"]
        if "image/png" in data:
            b64 = join(data["image/png"]).replace("\n", "")
            return f'<figure class="out-figure"><img alt="Graph diagram drawn by LangGraph" src="data:image/png;base64,{b64}"></figure>'
        if "text/markdown" in data:
            return f'<div class="out-md">{md.render(join(data["text/markdown"]))}</div>'
        if "text/plain" in data:
            return f'<pre class="out-text">{html.escape(join(data["text/plain"]))}</pre>'
    if kind == "error":
        text = ANSI.sub("", "\n".join(o.get("traceback", [])))
        return f'<pre class="out-text err">{html.escape(text)}</pre>'
    return ""


def build() -> str:
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    toc: list = []
    blocks = []
    for cell in nb["cells"]:
        source = join(cell["source"])
        if cell["cell_type"] == "markdown":
            blocks.append(f'<div class="md">{render_markdown(source, toc)}</div>')
        elif cell["cell_type"] == "code":
            if not source.strip():
                continue
            n = cell.get("execution_count")
            label = f"In [{n}]" if n else "In"
            outputs = "".join(render_output(o) for o in cell.get("outputs", []))
            out_html = f'<div class="cell-out"><span class="cell-label">Out</span>{outputs}</div>' if outputs else ""
            blocks.append(
                f'<div class="cell"><div class="cell-in"><span class="cell-label">{label}</span>'
                f'<pre class="code"><code>{code_html(source)}</code></pre></div>{out_html}</div>'
            )

    toc_html = "\n".join(f'<li><a href="#{a}">{html.escape(t)}</a></li>' for a, t in toc)
    return TEMPLATE.replace("{{TOC}}", toc_html).replace("{{BODY}}", "\n".join(blocks)).replace("{{REPO}}", REPO)


